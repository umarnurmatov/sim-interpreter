#pragma once

#include <cstdint>

#include "isa.hpp"

enum class Opcode : std::uint8_t
{
  kUnknown = 0,

  // Opcode in [5:0]
  kBdep,
  kNor,
  kCls,
  kSyscall,
  kAdd,

  // Opcode in [31:26]
  kSsat,
  kBeq,
  kLd,
  kCbit,
  kJ,
  kAddi,
  kJalr,
  kSt,
  kStp,
  kLi
};

struct InstrEncoding
{
  struct InstrFieldEncoding { 
      std::uint8_t width, 
                   offset;
  } 
  f1, f2, f3, f4;
};

// enumeration same as Opcode
constexpr InstrEncoding kInstrEnc[] = 
{
  { { 0x00, 0x00 }, { 0x00, 0x00 }, { 0x00, 0x00 }, { 0x00, 0x00 } }, // UNKNOWN
  { { 0x05, 0x0B }, { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x00, 0x00 } }, // BDEP:    rs2, rs1 , rd         , -
  { { 0x05, 0x0B }, { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x00, 0x00 } }, // NOR:     rd , rt  , rs         , -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x00, 0x00 }, { 0x00, 0x00 } }, // CLS:     rs , rd  , -          , -
  { { 0x00, 0x00 }, { 0x00, 0x00 }, { 0x00, 0x00 }, { 0x00, 0x00 } }, // SYSCALL: -  , -   , code       , -
  { { 0x05, 0x0B }, { 0x05, 0x15 }, { 0x05, 0x10 }, { 0x00, 0x00 } }, // ADD:     rd , rs  , rt         , -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x05, 0x0B }, { 0x00, 0x00 } }, // SSAT:    rs , rd  , imm5       , -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x10, 0x00 }, { 0x00, 0x00 } }, // BEQ:     rt , rs  , offst      , -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x0E, 0x00 }, { 0x00, 0x00 } }, // LD:      rt , base, imm        , -
  { { 0x05, 0x15 }, { 0x05, 0x10 }, { 0x05, 0x0B }, { 0x00, 0x00 } }, // CBIT:    rd , rs  , imm        , -
  { { 0x00, 0x00 }, { 0x00, 0x00 }, { 0x1A, 0x00 }, { 0x00, 0x00 } }, // J:       -  , -   , instr_index, -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x10, 0x00 }, { 0x00, 0x00 } }, // ADDI:    rt , rs  , imm        , -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x10, 0x00 }, { 0x00, 0x00 } }, // JALR:    rt , rs  , imm        , -
  { { 0x05, 0x10 }, { 0x05, 0x15 }, { 0x0E, 0x00 }, { 0x00, 0x00 } }, // ST:      rt , base, imm        , -
  { { 0x05, 0x10 }, { 0x05, 0x0B }, { 0x05, 0x15 }, { 0x0B, 0x00 } }, // STP:     rt1, rt2 , base       , offst
  { { 0x05, 0x10 }, { 0x00, 0x00 }, { 0x10, 0x00 }, { 0x00, 0x00 } }, // LI:      rt , -   , imm        , -
};

struct Instr
{
  Opcode opc{};

  Byte f1{},
       f2{};
  Word f3{}; // (f3 << width_f4) | f4
};
